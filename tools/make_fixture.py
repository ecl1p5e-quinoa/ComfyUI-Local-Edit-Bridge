"""Deterministic local-only smoke-test images (no model or external service)."""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, PngImagePlugin

target = Path(sys.argv[1])
target.mkdir(parents=True, exist_ok=True)
if len(sys.argv) > 2:
    with Image.open(sys.argv[2]) as image:
        image = image.convert("RGB")
        draw = ImageDraw.Draw(image)
        width, height = image.size
        draw.ellipse((width * .30, height * .30, width * .70, height * .70), fill="#367eeb")
        image.save(target / "returned.png")
else:
    y, x = np.mgrid[:480, :640]
    pixels = np.stack((40 + x // 8, 65 + y // 6, 85 + x // 10), axis=-1).astype(np.uint8)
    image = Image.fromarray(pixels)
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((90, 90, 550, 390), radius=32, fill="#ded6c1")
    draw.ellipse((260, 180, 380, 300), fill="#d8694c")
    draw.ellipse((279, 194, 310, 216), fill="#edb895")
    draw.rounded_rectangle((140, 320, 500, 336), radius=7, fill="#afab9e")
    draw.text((180, 130), "LOCAL EDIT / SYNTHETIC TEST", fill="#404d52")
    info = PngImagePlugin.PngInfo()
    info.add_text("parameters", "A geometric still life\nNegative prompt: noise\nSteps: 20, Sampler: Euler, CFG scale: 7, Seed: 42, Size: 640x480")
    info.add_text("local_edit_fixture", "Deterministic test fixture; not generated by a diffusion model.")
    image.save(target / "source.png", pnginfo=info)
