// Tests only the local plugin UI; never opens or automates ChatGPT.
const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const assert = require("node:assert/strict");

(async () => {
    const base = process.argv[2] || "http://127.0.0.1:8190";
    assert(["127.0.0.1", "localhost", "::1"].includes(new URL(base).hostname), "Local test server required");
    const python = process.argv[3];
    const output = path.resolve(".test-output");
    fs.mkdirSync(output, { recursive: true });
    execFileSync(python, ["tools/make_fixture.py", output]);
    const browser = await chromium.launch({ channel: "msedge", headless: true });
    let page;
    try {
        page = await browser.newPage({ viewport: { width: 1450, height: 1050 } });
        const errors = [];
        page.on("pageerror", error => errors.push(error.message));
        await page.goto(base + "/gpt-local-edit/editor");
        await page.waitForFunction(() => !document.querySelector("#source-file").disabled);
        await page.locator("#source-file").setInputFiles(path.join(output, "source.png"));
        await page.locator("#state").filter({ hasText: "DRAFT" }).waitFor();
        await page.waitForFunction(() => !document.querySelector("#brush-size").disabled);
        await page.locator("#brush-size").evaluate(element => {
            element.value = "96";
            element.dispatchEvent(new Event("input", { bubbles: true }));
        });
        const canvas = await page.locator("#canvas").boundingBox();
        await page.mouse.move(canvas.x + canvas.width / 2 - 8, canvas.y + canvas.height / 2);
        const ring = page.locator("#canvas-drop > div").last();
        assert.equal(await ring.evaluate(element => getComputedStyle(element).display), "block");
        const expectedDiameter = 96 * Math.min((canvas.width - 32) / 640, (canvas.height - 32) / 480);
        assert(Math.abs(await ring.evaluate(element => parseFloat(element.style.width)) - expectedDiameter) < 0.01);
        assert.equal(await ring.evaluate(element => getComputedStyle(element).backgroundColor), "rgba(0, 0, 0, 0)");
        await page.screenshot({ path: path.join(output, "brush-cursor.png") });
        await page.keyboard.down("Space");
        assert.equal(await ring.evaluate(element => getComputedStyle(element).display), "none");
        await page.keyboard.up("Space");
        await page.mouse.down();
        await page.mouse.move(canvas.x + canvas.width / 2 + 8, canvas.y + canvas.height / 2, { steps: 5 });
        await page.mouse.up();
        await page.waitForFunction(() => document.querySelector("#crop-info").textContent.includes("Bounds"));
        await page.keyboard.press("Control+z");
        await page.waitForFunction(() => !document.querySelector("#crop-info").textContent.includes("Bounds"));
        await page.keyboard.press("Control+Shift+z");
        await page.waitForFunction(() => document.querySelector("#crop-info").textContent.includes("Bounds"));
        await page.locator("#crop-factor").focus();
        await page.keyboard.press("ArrowRight");
        await page.waitForFunction(() => document.querySelector("#factor-value").textContent.includes("2.1"));
        await page.waitForTimeout(500);
        await page.locator("#request").fill("Turn the orange sphere blue. Keep its shape and the background.");
        await page.locator("#generate").click();
        await page.waitForFunction(() => document.querySelector("#prompt").value.length > 100);
        await page.waitForFunction(() => !document.querySelector("#prepare").disabled);
        const folderRequest = page.waitForResponse(response => response.url().endsWith("/open-handoff") && response.request().method() === "POST");
        await page.locator("#prepare").click();
        const folderResponse = await folderRequest;
        assert.equal(folderResponse.status(), 200);
        const handoff = (await folderResponse.json()).directory;
        assert.deepEqual(fs.readdirSync(handoff).sort(), ["01-crop.png", "02-overlay.png", "prompt.txt"]);
        await page.locator("#state").filter({ hasText: "READY FOR EXTERNAL EDIT" }).waitFor();
        const id = await page.locator("#job-id").innerText();
        const route = base + "/gpt-local-edit/jobs/" + id;
        let job = (await (await page.request.get(route)).json()).job;
        assert.equal(job.crop_settings.crop_factor, 2.1);
        const cropPath = path.join(output, "crop.png");
        fs.writeFileSync(cropPath, await (await page.request.get(route + "/files/crop.png")).body());
        assert.equal(job.handoff, "crop_overlay");
        assert.equal(await page.locator("#color-enabled").isChecked(), true);
        assert.equal(await page.locator("#strength").inputValue(), "1");
        assert((await page.locator("#open-overlay").getAttribute("href")).includes("overlay.png"));
        execFileSync(python, ["tools/make_fixture.py", output, cropPath]);
        await page.locator("#handoff-more summary").click();
        await page.locator("#sent").click();
        await page.locator("#state").filter({ hasText: "WAITING FOR RESULT" }).waitFor();
        await page.waitForFunction(() => !document.querySelector("#result-file").disabled);
        assert.equal(await page.locator("#import-policy").inputValue(), "contain");
        await page.locator("#import-policy").selectOption("strict");
        await page.locator("#result-file").setInputFiles(path.join(output, "source.png"));
        await page.waitForFunction(() => document.querySelector("#import-status").textContent.includes("aspect ratio"));
        assert(await page.locator("#import-status").isVisible());
        await page.locator("#import-policy").selectOption("contain");
        await page.locator("#retry-import").click();
        await page.waitForFunction(() => !document.body.classList.contains("busy"));
        assert.equal(await page.locator("#import-status").getAttribute("class"), "success");
        await page.locator("#import-policy").selectOption("strict");
        await page.locator("#result-file").setInputFiles(path.join(output, "returned.png"));
        await page.locator("#state").filter({ hasText: "RESULT IMPORTED" }).waitFor();
        await page.waitForFunction(() => !document.querySelector("#color-enabled").disabled);
        await page.locator("#color-enabled").check();
        assert.equal(await page.locator("#mask-expansion").inputValue(), "0");
        await page.locator("#mask-expansion").fill("6");
        await page.locator("#composite").click();
        await page.locator("#state").filter({ hasText: "COMPOSITED" }).waitFor();
        await page.waitForFunction(() => document.querySelector("#after-preview").naturalWidth === 640);
        await page.waitForFunction(() => !document.body.classList.contains("busy"));
        const maskCard = await page.locator('[data-step="mask"]').boundingBox();
        const cropCard = await page.locator('[data-step="crop"]').boundingBox();
        assert(Math.abs(maskCard.y - cropCard.y) < 2 && cropCard.x > maskCard.x);
        assert(await page.locator('[data-step="mask"] #brush-size').count());
        assert(await page.locator('[data-step="crop"] #crop-factor').count());
        const promptCard = await page.locator('[data-step="prompt"]').boundingBox();
        const importCard = await page.locator('[data-step="import"]').boundingBox();
        const blendCard = await page.locator('[data-step="blend"]').boundingBox();
        assert(importCard.y > promptCard.y && blendCard.y > importCard.y);
        await page.locator("#compare-frame").scrollIntoViewIfNeeded();
        const compare = await page.locator("#compare-frame").boundingBox();
        assert(compare.height >= 600);
        await page.mouse.move(compare.x + compare.width * 0.25, compare.y + compare.height / 2);
        assert(Math.abs(Number(await page.locator("#compare-position").inputValue()) - 25) < 1);
        await page.locator("#compare-mode").selectOption("click");
        await page.mouse.move(compare.x + compare.width / 2, compare.y + compare.height / 2);
        await page.mouse.down();
        assert.equal(await page.locator("#compare-position").inputValue(), "100");
        await page.mouse.up();
        assert.equal(await page.locator("#compare-position").inputValue(), "0");
        await page.locator("#compare-mode").selectOption("slide");
        await page.screenshot({ path: path.join(output, "editor-roundtrip.png"), fullPage: true });
        await page.locator("#finalize").click();
        await page.locator("#state").filter({ hasText: "FINALIZED" }).waitFor();
        job = (await (await page.request.get(route)).json()).job;
        for (const name of ["original.png", "mask.png", "final.png", job.files.seam]) {
            fs.writeFileSync(path.join(output, name), await (await page.request.get(route + "/files/" + name)).body());
        }
        await page.reload();
        await page.locator("#state").filter({ hasText: "FINALIZED" }).waitFor();
        assert.equal(await page.locator("#job-id").innerText(), id);
        assert.equal(await page.locator("#mask-expansion").inputValue(), "6");
        const originalPrompt = await page.locator("#prompt").inputValue();
        for (const step of ["mask", "crop", "prompt", "import", "blend", "final"]) {
            await page.locator(`[data-rework="${step}"]`).click();
            await page.waitForFunction(() => !document.body.classList.contains("busy"));
            const current = (await (await page.request.get(route)).json()).job;
            assert.equal(current.prompt, originalPrompt);
            assert.equal(current.files.final, undefined);
            if (step === "mask") assert.deepEqual(current.crop.bounds, job.crop.bounds);
            if (step === "prompt") assert.deepEqual(current.crop.bounds, job.crop.bounds);
            await page.reload();
            await page.locator(`[data-restore="${step}"]`).click();
            await page.locator("#state").filter({ hasText: "FINALIZED" }).waitFor();
            assert.equal(await page.locator("#prompt").inputValue(), originalPrompt);
        }
        await page.locator('[data-rework="prompt"]').click();
        await page.waitForFunction(() => !document.body.classList.contains("busy"));
        await page.locator("#prompt").fill("Typing stays in the prompt");
        await page.locator("#prompt").press("End");
        await page.keyboard.type("!");
        await page.keyboard.press("Control+z");
        assert.equal(await page.locator("#prompt").inputValue(), "Typing stays in the prompt");
        await page.locator('[data-restore="prompt"]').click();
        await page.locator("#state").filter({ hasText: "FINALIZED" }).waitFor();
        await page.setViewportSize({ width: 390, height: 844 });
        await page.waitForTimeout(100);
        const mobileMask = await page.locator('[data-step="mask"]').boundingBox();
        const mobileCrop = await page.locator('[data-step="crop"]').boundingBox();
        assert(mobileCrop.y >= mobileMask.y + mobileMask.height);
        assert(parseInt(await page.locator("#zoom").textContent()) < 60);
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
        await page.screenshot({ path: path.join(output, "editor-mobile.png"), fullPage: true });
        await page.evaluate(() => window.scrollTo(0, 0));
        await page.screenshot({ path: path.join(output, "editor-mobile-top.png") });
        assert.deepEqual(errors, []);
        fs.writeFileSync(path.join(output, "browser-report.json"), JSON.stringify({ job_id: id, state: job.state, errors, crop: job.crop }, null, 2));
        console.log(JSON.stringify({ passed: true, job_id: id, state: job.state, browser_errors: errors.length }));
    } catch (error) {
        if (page) {
            console.error("Editor status:", await page.locator("#message").textContent());
            await page.screenshot({ path: path.join(output, "browser-failure.png"), fullPage: true });
        }
        throw error;
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
